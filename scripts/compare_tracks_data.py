r"""TRICYS Track 1 vs Track 2 Quantitative Error Analysis and Comparison Engine.
=============================================================================
Compares optimization and simulation datasets generated by:
- Track 1 (Dual-Basis Closed-Form Direct Optimization)
- Track 2 (Rigid ODE Nested Bisection Optimization)

Computes:
1. Absolute Error (AE), Signed Error, and Relative Error (RE %) for Required TBR and Startup Inventory (I_S_0).
2. Statistical metrics: Mean Absolute Error (MAE), Root Mean Square Error (RMSE), and Max Error.
3. Generates:
   - Detailed CSV: v&v/data/tracks_error_comparison_detailed.csv
   - Summary CSV: v&v/data/tracks_error_comparison_summary.csv
   - Formal Markdown Report: v&v/data/tracks_error_comparison_report.md
   - Visualization Plots:
     * v&v/figures/comparison/parity_plot_tbr.png
     * v&v/figures/comparison/parity_plot_is0.png
     * v&v/figures/comparison/relative_error_distribution.png
"""

